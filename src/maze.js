function cloneMaze() {
  return MAZE_LAYOUT.map(r => [...r]);
}

function isWall(maze, x, y) {
  if (y < 0 || y >= maze.length || x < 0 || x >= maze[0].length) return false; // tunnel
  return maze[y][x] === 1;
}

function isDot(maze, x, y) {
  if (y < 0 || y >= maze.length || x < 0 || x >= maze[0].length) return false;
  return maze[y][x] === 2;
}

function isPowerPellet(maze, x, y) {
  if (y < 0 || y >= maze.length || x < 0 || x >= maze[0].length) return false;
  return maze[y][x] === 3;
}
